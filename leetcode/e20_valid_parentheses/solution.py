"""20. 有效的括号

https://leetcode.cn/problems/valid-parentheses/

字符串 s 只含 '()[]{}'，判断是否有效。

决定性条件：
- 有效不只是左右括号「个数相等」：还要类型一致，且后开的必须先关（栈的 LIFO 顺序）。
- `(` 必须配 `)`，不能配 `]`；`([)]` 虽然每种括号数量都是 1，但交叉闭合无效。
- 右括号出现时，必须马上和「当前还没关的最内层」左括号配对，不能和更早的左括号配。

不变量：
- 栈中保存尚未闭合的左括号，从栈底到栈顶 = 从外到内的嵌套顺序。
- 扫描到位置 i 之前，栈里每个左括号都还没有遇到与之配对的右括号。
- 遇到右括号时：栈顶就是唯一合法的配对对象；栈空则说明多出一个右括号。

步骤：
1. 长度为奇数时不可能全部配对，直接返回 False（必要条件，不能替代类型检查）。
2. 用字典记录左括号到右括号的映射。
3. 遍历每个字符：若是左括号则压栈；若是右括号则栈空返回 False，否则弹出栈顶，与当前字符按字典核对是否匹配，不匹配返回 False。
4. 遍历结束，栈必须为空；非空说明还有左括号未闭合。

例 `([])`：依次压入 `(`、`[`，`]` 与栈顶 `[` 配对后剩 `(`，`)` 与栈顶 `(` 配对，栈空 → True。
例 `(])`：`(` 入栈后遇 `]`，弹出 `(`，期望 `)` 实为 `]` → False。
例 `([)]`：压入 `(`、`[` 后遇 `)`，弹出 `[`，期望 `]` 实为 `)` → False。

复杂度：时间 O(n)，空间 O(n)。
"""


def is_valid(s: str) -> bool:
    if len(s) % 2 != 0:
        return False

    d = {"{": "}", "[": "]", "(": ")"}

    stack = []
    for c in s:
        if c in d:
            stack.append(c)
        elif not stack:
            return False
        elif c != d[stack.pop()]:
            return False

    return len(stack) == 0
